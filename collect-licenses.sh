#!/bin/bash
# Write <out-dir>/third-party.txt: the license texts of everything dist/ bundles. Runs in the
# image (build.sh): the components' files kept by add-license.sh in $PREFIX/share/licenses, plus
# Ubuntu's copyright files of the DejaVu font and the CA list copied from the image. Identical
# texts (ignoring whitespace) are written once. A single file: the SD card is exFAT, where every
# small file takes 128 KB.
set -e
OUT=$1
L=$PREFIX/share/licenses
declare -A seen

text() {  # <label> <file>: the text, or a pointer to the identical one written before
    local h
    h=$(tr -d ' \t\n\r\f\v' < "$2" | md5sum | cut -d' ' -f1)  # copies differ in whitespace/wrapping
    if [ -n "${seen[$h]}" ]; then
        printf -- '---- %s: the same text as "%s" above\n\n' "$1" "${seen[$h]}"
    else
        seen[$h]=$1
        printf -- '---- %s\n\n' "$1"; cat "$2"; printf '\n\n'
    fi
}

rule() { printf '%s\n' "===================================================================================================="; }

# mpv and FFmpeg first, then the libraries
components=(mpv ffmpeg $(ls "$L" | grep -v -x -e mpv -e ffmpeg))
ubuntu=(fonts-dejavu-core ca-certificates)
{
    echo "mpv for TrimUI Smart Pro (mpv-tsp): third-party licenses"
    echo
    echo "mpv-tsp's build scripts are MIT licensed (LICENSE in this folder); its changes to mpv and FFmpeg"
    echo "(context_sdl.c, cedar/cedardec.c) are LGPL-2.1-or-later like them. Everything in this package"
    echo "is listed below with its license texts. Sources: https://github.com/matweew/mpv-tsp, whose"
    echo "Dockerfile builds each component from the source given here. Generated by build.sh."
    echo
    for c in "${components[@]}"; do echo "- $(head -1 "$L/$c/ABOUT")"; done
    echo "- DejaVu Sans font (fonts/), CA certificates (ca-certificates.crt): Ubuntu 20.04 packages"
    echo
    for c in "${components[@]}"; do
        rule; cat "$L/$c/ABOUT"; rule; echo
        for f in "$L/$c"/*; do
            [ "${f##*/}" = ABOUT ] || text "$c: ${f##*/}" "$f"
        done
    done
    for pkg in "${ubuntu[@]}"; do
        rule; echo "$pkg (Ubuntu 20.04 package)"; echo "Source: https://packages.ubuntu.com/focal/$pkg"; rule; echo
        text "$pkg: /usr/share/doc/$pkg/copyright" "/usr/share/doc/$pkg/copyright"
    done
    # Texts the Ubuntu copyright files refer to
    copyrights=()
    for pkg in "${ubuntu[@]}"; do copyrights+=("/usr/share/doc/$pkg/copyright"); done
    for name in $(grep -ho '/usr/share/common-licenses/[A-Za-z0-9.+-]*[A-Za-z0-9+]' "${copyrights[@]}" | sort -u); do
        [ -f "$name" ] || continue
        rule; echo "$name"; rule; echo
        text "$name" "$(readlink -f "$name")"
    done
} > "$OUT/third-party.txt"
echo "licenses: ${#components[@]} components, $(( $(stat -c %s "$OUT/third-party.txt") / 1024 )) KB"
